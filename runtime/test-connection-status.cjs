'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const os = require('node:os');
const { randomBytes } = require('node:crypto');
const { createConnectionReporter, readConnectionStatus } = require('./connection-status.cjs');
(async () => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'background-browser-connection-status-'));
  let clock = Date.parse('2026-10-27T18:00:00.000Z'), checks = 0;
  const now = () => clock;
  const check = (value, label) => { assert.ok(value, label); checks++; };
  const directory = path.join(root, 'setup', 'connection-observations');
  const read = () => readConnectionStatus(root, { now });
  const corruptFile = () => path.join(directory, 'chatgpt-' + randomBytes(16).toString('hex') + '-1.json');
  try {
    check((await read()).chatgpt.state === 'unseen', 'no request is not proof of a working ChatGPT connection');
    assert.throws(() => createConnectionReporter({ root, channel: 'arbitrary-private-content' })); checks++;
    const hosted = createConnectionReporter({ root, channel: 'chatgpt', now });
    const native = createConnectionReporter({ root, channel: 'codex', now });
    await hosted.failure('BACKEND_UNAVAILABLE', 'not-dispatched');
    let status = await read();
    check(status.chatgpt.state === 'failed' && status.chatgpt.failureCode === 'BACKEND_UNAVAILABLE', 'final request failure is durable');
    check(status.chatgpt.lastSuccessAt === null && status.chatgpt.lastContactAt === new Date(clock).toISOString(), 'failure contact never invents success');
    check(status.codex.state === 'unseen', 'hosted failure does not poison native status');
    clock += 10;
    await native.success();
    check((await read()).chatgpt.state === 'failed' && (await read()).codex.state === 'succeeded', 'native success cannot clear a ChatGPT failure');
    clock += 10;
    await hosted.failure('COMPLETION_UNKNOWN', 'unknown');
    const failureTime = new Date(clock).toISOString();
    clock += 10;
    await hosted.success();
    status = await read();
    check(status.chatgpt.state === 'succeeded' && status.chatgpt.lastSuccessAt === new Date(clock).toISOString(), 'later delivered browser request establishes connection recovery');
    check(status.chatgpt.lastFailureAt === failureTime && status.chatgpt.completion === 'unknown', 'recovery preserves earlier uncertain-action history');
    check(status.chatgpt.failureCode === 'COMPLETION_UNKNOWN', 'historical failure code is retained');
    const tieRoot = path.join(root, 'tie-case');
    await fs.mkdir(tieRoot);
    let tiedClock = clock - 10;
    const successWithHistory = createConnectionReporter({ root: tieRoot, channel: 'chatgpt', now: () => tiedClock });
    await successWithHistory.failure('COMPLETION_UNKNOWN', 'unknown');
    tiedClock = clock; await successWithHistory.success();
    // Race another reporter's ordinary failure against a success that carries
    // historical uncertainty, at the same completion millisecond.
    await createConnectionReporter({ root: tieRoot, channel: 'chatgpt', now }).failure('BACKEND_UNAVAILABLE', 'not-dispatched');
    check((await readConnectionStatus(tieRoot, { now })).chatgpt.state === 'failed', 'current failure wins a same-millisecond tie against success carrying historical uncertainty');
    const restarted = createConnectionReporter({ root, channel: 'chatgpt', now });
    clock += 10;
    await restarted.success();
    check((await read()).chatgpt.lastFailureAt === failureTime, 'new reporter process does not erase earlier failure metadata');
    clock += 10;
    await hosted.failure('FIXTURE_PRIVATE_ERROR_TEXT', 'https://private.invalid/?token=FIXTURE_NOT_REAL');
    status = await read();
    check(status.chatgpt.failureCode === 'REQUEST_FAILED' && status.chatgpt.completion === 'unknown', 'arbitrary reporter inputs become fixed enums');
    const serialized = JSON.stringify(status);
    check(!serialized.includes('FIXTURE_PRIVATE') && !serialized.includes('private.invalid') && !serialized.includes('token='), 'raw diagnostics and URLs never reach status');
    const stored = await Promise.all((await fs.readdir(directory)).filter(name => name.endsWith('.json')).map(name => fs.readFile(path.join(directory, name), 'utf8')));
    check(!stored.join('').includes('FIXTURE_PRIVATE') && !stored.join('').includes('private.invalid'), 'raw input never enters durable records');
    check(Object.keys(status.chatgpt).sort().join(',') === ['state', 'lastContactAt', 'lastSuccessAt', 'lastFailureAt', 'failureCode', 'completion'].sort().join(','), 'projection exposes exactly safe contract fields');
    const bad = corruptFile();
    await fs.writeFile(bad, '{invalid');
    check((await read()).chatgpt.state === 'unavailable' && (await read()).codex.state === 'succeeded', 'malformed observation fails closed for its channel only');
    await fs.unlink(bad);
    const recordFile = (await fs.readdir(directory)).find(name => name.startsWith('chatgpt-') && name.endsWith('.json'));
    const record = JSON.parse(await fs.readFile(path.join(directory, recordFile), 'utf8'));
    const future = corruptFile();
    await fs.writeFile(future, JSON.stringify({ ...record, lastContactAt: new Date(clock + 120000).toISOString() }));
    check((await read()).chatgpt.state === 'unavailable', 'future timestamps are never accepted');
    await fs.unlink(future);
    const large = corruptFile();
    await fs.writeFile(large, 'x'.repeat(2049));
    check((await read()).chatgpt.state === 'unavailable', 'oversized observations fail closed');
    await fs.unlink(large);
    const extra = corruptFile();
    await fs.writeFile(extra, JSON.stringify({ ...record, privateContent: 'FIXTURE_PRIVATE' }));
    check((await read()).chatgpt.state === 'unavailable' && !JSON.stringify(await read()).includes('FIXTURE_PRIVATE'), 'unexpected private fields are rejected without forwarding');
    await fs.unlink(extra);
    const wrong = corruptFile();
    await fs.writeFile(wrong, JSON.stringify({ ...record, channel: 'codex' }));
    check((await read()).chatgpt.state === 'unavailable', 'filename-channel mismatch is rejected');
    await fs.unlink(wrong);
    const a = createConnectionReporter({ root, channel: 'chatgpt', now });
    const b = createConnectionReporter({ root, channel: 'chatgpt', now });
    clock += 100;
    await Promise.all([a.success(), b.failure('CLIENT_DISCONNECTED', 'unknown')]);
    check((await read()).chatgpt.state === 'failed', 'same-timestamp failure wins conservatively across writers');
    const writers = Array.from({ length: 4 }, () => createConnectionReporter({ root, channel: 'codex', now: () => ++clock }));
    await Promise.all(writers.map(async writer => { for (let i = 0; i < 24; i++) await writer.success(); }));
    check((await read()).chatgpt.state === 'failed', 'bounded native history never evicts the other channel failure');
    check((await read()).codex.state === 'succeeded', 'concurrent native writers leave valid outcome receipts');
    check((await fs.readdir(directory)).filter(name => name.startsWith('codex-') && name.endsWith('.json')).length <= 64, 'per-channel storage is bounded after concurrent writes');
    check((await fs.readdir(directory)).every(name => !name.endsWith('.tmp')), 'atomic publication leaves no temporary artifacts');
    const restartedRead = await readConnectionStatus(root, { now });
    check(restartedRead.chatgpt.state === 'failed', 'failure survives reader/service recreation');
    const historicalFailure = restartedRead.chatgpt.lastFailureAt;
    const manySuccesses = createConnectionReporter({ root, channel: 'chatgpt', now: () => ++clock });
    for (let i = 0; i < 75; i++) await manySuccesses.success();
    check((await read()).chatgpt.state === 'succeeded' && (await read()).chatgpt.lastFailureAt === historicalFailure, 'pruning after a new reporter recovers retains historical failure evidence');
    check((await fs.readdir(directory)).filter(name => name.startsWith('chatgpt-') && name.endsWith('.json')).length <= 64, 'same-channel history remains bounded while retaining earlier failure');
    const blocked = path.join(root, 'not-a-directory');
    await fs.writeFile(blocked, 'fixture');
    const unavailableWriter = createConnectionReporter({ root: blocked, channel: 'codex', now });
    await assert.doesNotReject(unavailableWriter.failure('BACKEND_UNAVAILABLE', 'not-dispatched')); checks++;
    check((await readConnectionStatus(blocked, { now })).codex.state === 'unavailable', 'inaccessible storage is not presented as connected');
    console.log(JSON.stringify({ ok: true, checks, fixtureFilesOnly: true, browserLaunched: false, actualAccountDataRead: false }));
  } finally {
    if (path.dirname(path.resolve(root)) !== path.resolve(os.tmpdir()) || !path.basename(root).startsWith('background-browser-connection-status-')) throw new Error('Unsafe test cleanup.');
    await fs.rm(root, { recursive: true, force: true });
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
