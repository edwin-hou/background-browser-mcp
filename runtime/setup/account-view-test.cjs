'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const { createHash } = require('node:crypto');
const { accountStates, syncSavedSession } = require('./portal.cjs');
(async () => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'background-browser-account-view-'));
  let checks = 0;
  const check = (value, message) => { assert.ok(value, message); checks++; };
  try {
    const directory = path.join(root, 'setup', 'account-observations');
    await fs.mkdir(directory, { recursive: true });
    const site = { id: 'fixture-account', lastSavedAt: new Date(Date.now() - 60000).toISOString() };
    const filename = path.join(directory, createHash('sha256').update(site.id).digest('hex') + '.json');
    const put = value => fs.writeFile(filename, JSON.stringify(value));
    const state = () => accountStates(root, [site])[0];
    check(state().state === 'not-checked', 'a saved checkpoint never establishes authentication');
    check(state().lastVerifiedAt === null, 'an account without observations has no verification history');
    const required = { version: 1, siteId: site.id, state: 'sign-in-required', observedAt: new Date().toISOString(), reasonCode: 'known-login-form' };
    await put(required);
    check(state().state === 'sign-in-required', 'observed sign-in requirement is shown');
    check(state().lastVerifiedAt === null, 'sign-in-required evidence never implies previous verified access');
    await put({ ...required, state: 'verified' });
    check(state().state === 'verified', 'recent protected-page evidence is shown as last verified access');
    check(state().observedAt === required.observedAt && state().lastVerifiedAt === required.observedAt, 'current proof retains its existing timestamp and adds normalized history');
    const oldVerifiedAt = new Date(Date.now() - 90000000).toISOString();
    await put({ ...required, state: 'verified', observedAt: oldVerifiedAt });
    const expired = accountStates(root, [{ ...site, lastSavedAt: new Date(Date.now() - 172800000).toISOString() }])[0];
    check(expired.state === 'not-checked' && expired.observedAt === null, 'verification older than 24 hours becomes unknown even without a newer save');
    check(expired.lastVerifiedAt === oldVerifiedAt, 'stale verification remains available only as historical metadata');
    await put({ ...required, state: 'verified' });
    const savedAfterVerification = accountStates(root, [{ ...site, lastSavedAt: new Date(Date.now() + 1000).toISOString() }])[0];
    check(savedAfterVerification.state === 'not-checked' && savedAfterVerification.observedAt === null && savedAfterVerification.lastVerifiedAt === required.observedAt, 'a newer checkpoint invalidates current proof while preserving historical verification');
    await put({ ...required, state: 'verified', observedAt: '2020-01-02T03:04:05+00:00' });
    check(state().lastVerifiedAt === '2020-01-02T03:04:05.000Z', 'historical timestamps are normalized to an ISO date');
    await put(required);
    const reconnected = accountStates(root, [{ ...site, lastSavedAt: new Date(Date.now() + 1000).toISOString() }])[0];
    check(reconnected.state === 'not-checked', 'saving a newer session clears old attention without claiming authentication');
    const store = { markSaved(id, savedAt) { if (id === site.id) site.lastSavedAt = savedAt; } };
    syncSavedSession(store, { active: false, status: 'session-saved', siteId: site.id, savedAt: new Date(Date.now() + 1000).toISOString() });
    check(state().state === 'not-checked', 'a window-close save synchronizes the checkpoint before the polled account view');
    site.lastSavedAt = new Date(Date.now() - 60000).toISOString();
    await put({ ...required, state: 'verified', siteId: 'other-account' });
    check(state().state === 'not-checked' && state().lastVerifiedAt === null, 'another account observation cannot supply status or verification history');
    await put({ ...required, state: 'arbitrary-state' });
    check(state().state === 'not-checked' && state().lastVerifiedAt === null, 'unrecognized status or its history is not exposed');
    await put({ ...required, state: 'verified', observedAt: new Date(Date.now() + 120000).toISOString() });
    check(state().state === 'not-checked' && state().lastVerifiedAt === null, 'future evidence and verification history are rejected');
    await put({ ...required, state: 'verified', observedAt: 'not-a-date' });
    check(state().state === 'not-checked' && state().lastVerifiedAt === null, 'invalid dates cannot supply verification history');
    await put({ ...required, state: 'verified', observedAt: 1234 });
    check(state().state === 'not-checked' && state().lastVerifiedAt === null, 'non-string dates cannot supply verification history');
    await put({ ...required, state: 'verified', version: 2 });
    check(state().state === 'not-checked' && state().lastVerifiedAt === null, 'unrecognized observation versions cannot supply verification history');
    await put({ ...required, privateData: 'FIXTURE_PRIVATE_CONTENT_NOT_A_REAL_SECRET' });
    check(!JSON.stringify(state()).includes('FIXTURE_PRIVATE_CONTENT'), 'the view never forwards extra private fields');
    await fs.writeFile(filename, '{malformed');
    check(state().state === 'not-checked' && state().lastVerifiedAt === null, 'invalid local state supplies neither status nor verification history');
    check(accountStates(root, []).length === 0, 'removed or unrelated accounts are never enumerated');
    console.log(JSON.stringify({ ok: true, checks, browserLaunched: false, actualAccountDataRead: false }));
  } finally {
    const actual = path.resolve(root);
    if (path.dirname(actual) !== path.resolve(os.tmpdir()) || !path.basename(actual).startsWith('background-browser-account-view-')) throw new Error('Fixture cleanup boundary failed.');
    await fs.rm(actual, { recursive: true, force: true });
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
